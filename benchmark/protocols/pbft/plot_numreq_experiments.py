#!/usr/bin/env python3
"""
plot_numreq_experiments.py

Plot latency and throughput trends vs num_requests for TCP, RDMA, and basic_ring.

Expected input:
- One or more CSV files generated by your experiment runner.
- Each CSV should contain at least:
    variant
    result_num_requests   (or num_requests)
    result_avg_us
    result_p50_us
    result_p95_us
    result_p99_us
    result_throughput_rps
    result_status         (optional, used to filter only successful runs)

Typical usage:
    python3 plot_numreq_experiments.py \
        --csvs results_5.csv results_10.csv results_15.csv results_20.csv results_25.csv \
        --outdir plots

Or if all data is already in one CSV:
    python3 plot_numreq_experiments.py \
        --csvs merged_results.csv \
        --outdir plots

Optional:
    --variants tcp rdma basic_ring
    --title-prefix "ResilientDB PBFT"

Outputs:
- avg_latency_vs_num_requests.png
- throughput_vs_num_requests.png
- p50_latency_vs_num_requests.png
- p95_latency_vs_num_requests.png
- p99_latency_vs_num_requests.png
- percentile_panel.png
- tcp_normalized_speedup_latency.png
- summary_stats.csv
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path
from typing import List

import matplotlib.pyplot as plt
import pandas as pd


VARIANT_ORDER = ["tcp", "rdma", "basic_ring"]
VARIANT_STYLES = {
    "tcp": {"color": "#4C78A8", "marker": "o", "linestyle": "-"},
    "rdma": {"color": "#F58518", "marker": "s", "linestyle": "-"},
    "basic_ring": {"color": "#54A24B", "marker": "^", "linestyle": "-"},
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Plot latency/throughput trends vs num_requests.")
    parser.add_argument(
        "--csvs",
        nargs="+",
        required=True,
        help="One or more CSV files from run_experiments.py",
    )
    parser.add_argument(
        "--outdir",
        default="plots_numreq",
        help="Directory to save plots and summary CSV",
    )
    parser.add_argument(
        "--variants",
        nargs="+",
        default=VARIANT_ORDER,
        help="Variants to include, e.g. tcp rdma basic_ring",
    )
    parser.add_argument(
        "--title-prefix",
        default="ResilientDB PBFT",
        help="Prefix added to plot titles",
    )
    return parser.parse_args()


def load_data(csv_paths: List[str]) -> pd.DataFrame:
    dfs = []
    for path in csv_paths:
        df = pd.read_csv(path)
        df["source_csv"] = os.path.basename(path)
        dfs.append(df)
    if not dfs:
        raise ValueError("No CSV data loaded.")
    df = pd.concat(dfs, ignore_index=True)

    # Normalize request-count column.
    if "result_num_requests" in df.columns:
        df["plot_num_requests"] = df["result_num_requests"]
    elif "num_requests" in df.columns:
        df["plot_num_requests"] = df["num_requests"]
    else:
        raise ValueError("Expected 'result_num_requests' or 'num_requests' column in CSV.")

    # Keep only successful rows if result_status exists.
    if "exit_code" in df.columns:
        df = df[df["exit_code"] == 0].copy()

    if "result_status" in df.columns:
        df = df[df["result_status"] == "OK"].copy()

    # Keep only rows with required metrics.
    required_cols = [
        "variant",
        "plot_num_requests",
        "result_avg_us",
        "result_p50_us",
        "result_p95_us",
        "result_p99_us",
        "result_throughput_rps",
    ]
    missing = [c for c in required_cols if c not in df.columns]
    if missing:
        raise ValueError(f"Missing required columns: {missing}")

    df["plot_num_requests"] = pd.to_numeric(df["plot_num_requests"], errors="coerce")
    for col in [
        "result_avg_us",
        "result_p50_us",
        "result_p95_us",
        "result_p99_us",
        "result_throughput_rps",
    ]:
        df[col] = pd.to_numeric(df[col], errors="coerce")

    df = df.dropna(
        subset=[
            "variant",
            "plot_num_requests",
            "result_avg_us",
            "result_p50_us",
            "result_p95_us",
            "result_p99_us",
            "result_throughput_rps",
        ]
    ).copy()

    return df


def summarize(df: pd.DataFrame) -> pd.DataFrame:
    grouped = (
        df.groupby(["variant", "plot_num_requests"], as_index=False)
        .agg(
            avg_us_mean=("result_avg_us", "mean"),
            avg_us_std=("result_avg_us", "std"),
            p50_us_mean=("result_p50_us", "mean"),
            p50_us_std=("result_p50_us", "std"),
            p95_us_mean=("result_p95_us", "mean"),
            p95_us_std=("result_p95_us", "std"),
            p99_us_mean=("result_p99_us", "mean"),
            p99_us_std=("result_p99_us", "std"),
            throughput_mean=("result_throughput_rps", "mean"),
            throughput_std=("result_throughput_rps", "std"),
            count=("result_avg_us", "count"),
        )
    )
    grouped = grouped.sort_values(["variant", "plot_num_requests"]).reset_index(drop=True)
    return grouped


def apply_matplotlib_style() -> None:
    plt.rcParams.update({
        "figure.figsize": (8.5, 5.2),
        "figure.dpi": 140,
        "axes.grid": True,
        "grid.alpha": 0.25,
        "grid.linestyle": "--",
        "axes.spines.top": False,
        "axes.spines.right": False,
        "axes.titlesize": 13,
        "axes.labelsize": 11,
        "legend.fontsize": 10,
        "xtick.labelsize": 10,
        "ytick.labelsize": 10,
        "lines.linewidth": 2.0,
    })


def plot_metric_vs_requests(
    summary: pd.DataFrame,
    variants: List[str],
    mean_col: str,
    std_col: str,
    ylabel: str,
    title: str,
    outpath: str,
) -> None:
    fig, ax = plt.subplots()

    for variant in variants:
        sdf = summary[summary["variant"] == variant].sort_values("plot_num_requests")
        if sdf.empty:
            continue
        style = VARIANT_STYLES.get(
            variant,
            {"color": "#333333", "marker": "o", "linestyle": "-"},
        )
        ax.errorbar(
            sdf["plot_num_requests"],
            sdf[mean_col],
            yerr=sdf[std_col].fillna(0),
            label=variant,
            color=style["color"],
            marker=style["marker"],
            linestyle=style["linestyle"],
            capsize=4,
        )

    ax.set_xlabel("Number of requests")
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(outpath, bbox_inches="tight")
    plt.close(fig)


def plot_percentile_panel(
    summary: pd.DataFrame,
    variants: List[str],
    title_prefix: str,
    outpath: str,
) -> None:
    fig, axes = plt.subplots(1, 3, figsize=(15, 4.5), sharex=True)

    percentile_specs = [
        ("p50_us_mean", "p50_us_std", "P50 Latency (us)"),
        ("p95_us_mean", "p95_us_std", "P95 Latency (us)"),
        ("p99_us_mean", "p99_us_std", "P99 Latency (us)"),
    ]

    for ax, (mean_col, std_col, ylabel) in zip(axes, percentile_specs):
        for variant in variants:
            sdf = summary[summary["variant"] == variant].sort_values("plot_num_requests")
            if sdf.empty:
                continue
            style = VARIANT_STYLES.get(
                variant,
                {"color": "#333333", "marker": "o", "linestyle": "-"},
            )
            ax.errorbar(
                sdf["plot_num_requests"],
                sdf[mean_col],
                yerr=sdf[std_col].fillna(0),
                label=variant,
                color=style["color"],
                marker=style["marker"],
                linestyle=style["linestyle"],
                capsize=4,
            )
        ax.set_xlabel("Number of requests")
        ax.set_ylabel(ylabel)
        ax.grid(True, alpha=0.25, linestyle="--")

    axes[0].set_title(f"{title_prefix}: P50")
    axes[1].set_title(f"{title_prefix}: P95")
    axes[2].set_title(f"{title_prefix}: P99")
    axes[2].legend(frameon=False)
    fig.tight_layout()
    fig.savefig(outpath, bbox_inches="tight")
    plt.close(fig)


def plot_latency_speedup(summary: pd.DataFrame, variants: List[str], title_prefix: str, outpath: str) -> None:
    tcp = summary[summary["variant"] == "tcp"][["plot_num_requests", "avg_us_mean"]].copy()
    if tcp.empty:
        return
    tcp = tcp.rename(columns={"avg_us_mean": "tcp_avg_us_mean"})

    merged = summary.merge(tcp, on="plot_num_requests", how="left")
    merged["latency_speedup_vs_tcp"] = merged["tcp_avg_us_mean"] / merged["avg_us_mean"]

    fig, ax = plt.subplots()
    for variant in variants:
        if variant == "tcp":
            continue
        sdf = merged[merged["variant"] == variant].sort_values("plot_num_requests")
        if sdf.empty:
            continue
        style = VARIANT_STYLES.get(
            variant,
            {"color": "#333333", "marker": "o", "linestyle": "-"},
        )
        ax.plot(
            sdf["plot_num_requests"],
            sdf["latency_speedup_vs_tcp"],
            label=variant,
            color=style["color"],
            marker=style["marker"],
            linestyle=style["linestyle"],
        )

    ax.axhline(1.0, color="gray", linestyle="--", linewidth=1)
    ax.set_xlabel("Number of requests")
    ax.set_ylabel("Latency speedup vs TCP (higher is better)")
    ax.set_title(f"{title_prefix}: Average Latency Speedup vs TCP")
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(outpath, bbox_inches="tight")
    plt.close(fig)


def main() -> None:
    args = parse_args()
    apply_matplotlib_style()

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    df = load_data(args.csvs)
    df = df[df["variant"].isin(args.variants)].copy()

    # Preserve a sensible plotting order.
    variant_rank = {v: i for i, v in enumerate(VARIANT_ORDER)}
    df["variant_rank"] = df["variant"].map(lambda v: variant_rank.get(v, 999))
    df = df.sort_values(["variant_rank", "plot_num_requests"]).drop(columns=["variant_rank"])

    summary = summarize(df)
    summary.to_csv(outdir / "summary_stats.csv", index=False)

    title_prefix = args.title_prefix

    plot_metric_vs_requests(
        summary,
        args.variants,
        mean_col="avg_us_mean",
        std_col="avg_us_std",
        ylabel="Average latency (us)",
        title=f"{title_prefix}: Average Latency vs Number of Requests",
        outpath=str(outdir / "avg_latency_vs_num_requests.png"),
    )

    plot_metric_vs_requests(
        summary,
        args.variants,
        mean_col="throughput_mean",
        std_col="throughput_std",
        ylabel="Throughput (requests/sec)",
        title=f"{title_prefix}: Throughput vs Number of Requests",
        outpath=str(outdir / "throughput_vs_num_requests.png"),
    )

    plot_metric_vs_requests(
        summary,
        args.variants,
        mean_col="p50_us_mean",
        std_col="p50_us_std",
        ylabel="P50 latency (us)",
        title=f"{title_prefix}: P50 Latency vs Number of Requests",
        outpath=str(outdir / "p50_latency_vs_num_requests.png"),
    )

    plot_metric_vs_requests(
        summary,
        args.variants,
        mean_col="p95_us_mean",
        std_col="p95_us_std",
        ylabel="P95 latency (us)",
        title=f"{title_prefix}: P95 Latency vs Number of Requests",
        outpath=str(outdir / "p95_latency_vs_num_requests.png"),
    )

    plot_metric_vs_requests(
        summary,
        args.variants,
        mean_col="p99_us_mean",
        std_col="p99_us_std",
        ylabel="P99 latency (us)",
        title=f"{title_prefix}: P99 Latency vs Number of Requests",
        outpath=str(outdir / "p99_latency_vs_num_requests.png"),
    )

    plot_percentile_panel(
        summary,
        args.variants,
        title_prefix=title_prefix,
        outpath=str(outdir / "percentile_panel.png"),
    )

    plot_latency_speedup(
        summary,
        args.variants,
        title_prefix=title_prefix,
        outpath=str(outdir / "tcp_normalized_speedup_latency.png"),
    )

    print(f"[OK] Wrote plots and summary CSV to: {outdir}")


if __name__ == "__main__":
    main()